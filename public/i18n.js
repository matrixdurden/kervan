function initialLang() {
  try {
    const saved = localStorage.getItem("kervan.lang");
    if (LANGS.includes(saved)) return saved;
  } catch { /* yok say */ }
  return (globalThis.navigator?.language || "").toLowerCase().startsWith("ar") ? "ar" : "tr";
}

export let lang = initialLang();

export function setLang(next) {
  lang = next;
  try { localStorage.setItem("kervan.lang", next); } catch { /* yok say */ }
  applyStatic();
}

export function t(key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.tr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

export const unitLabel = (unit) => UNIT_NAMES[lang]?.[unit] ?? unit ?? "";

// HTML'deki data-i18n* öznitelikli öğeleri seçili dile çevirir.
export function applyStatic() {
  if (typeof document === "undefined") return; // testlerde
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll("[data-i18n-label]")) el.setAttribute("aria-label", t(el.dataset.i18nLabel));
}
